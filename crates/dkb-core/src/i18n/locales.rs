#![allow(clippy::match_same_arms, clippy::too_many_lines)]

use super::Language;

pub fn lookup(lang: Language, key: &str) -> Option<&'static str> {
    match lang {
        Language::Auto => None,
        Language::EnUs | Language::EnAu | Language::EnCa | Language::EnIn | Language::EnJp | Language::EnGb => {
            lookup_en(key)
        }
        Language::De => lookup_de(key),
        Language::EsEs | Language::EsCl | Language::Es419 | Language::EsMx | Language::EsUs => {
            match lang {
                Language::EsMx => lookup_es_mx(key).or_else(|| lookup_es(key)),
                _ => lookup_es(key),
            }
        }
        Language::FrFr => lookup_fr(key),
        Language::FrCa => lookup_fr_ca(key).or_else(|| lookup_fr(key)),
        Language::Ja => lookup_ja(key),
        Language::ZhHans => lookup_zh_hans(key),
        Language::ZhHant => lookup_zh_hant(key),
        Language::It => lookup_it(key),
        Language::PtPt => lookup_pt_pt(key),
        Language::PtBr => lookup_pt_br(key).or_else(|| lookup_pt_pt(key)),
        Language::Ru => lookup_ru(key),
        Language::Ko => lookup_ko(key),
        Language::Nl => lookup_nl(key),
        Language::Ar => lookup_ar(key),
        Language::Ca => lookup_ca(key),
        Language::Hr => lookup_hr(key),
        Language::Cs => lookup_cs(key),
        Language::Da => lookup_da(key),
        Language::Fi => lookup_fi(key),
        Language::El => lookup_el(key),
        Language::He => lookup_he(key),
        Language::Hi => lookup_hi(key),
        Language::Hu => lookup_hu(key),
        Language::Id => lookup_id(key),
        Language::Ms => lookup_ms(key),
        Language::Nb => lookup_nb(key),
        Language::Pl => lookup_pl(key),
        Language::Ro => lookup_ro(key),
        Language::Sk => lookup_sk(key),
        Language::Sv => lookup_sv(key),
        Language::Th => lookup_th(key),
        Language::Tr => lookup_tr(key),
        Language::Uk => lookup_uk(key),
        Language::Vi => lookup_vi(key),
    }
}

